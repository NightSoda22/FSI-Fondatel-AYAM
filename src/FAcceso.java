    private void BAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BAceptarActionPerformed
        String usr = TUsuario.getText();
        String nip = TPassword.getText();

        String sql = String.format(rol, usr, nip);
        String tipo = cnx.obtenerDato(sql);

        switch (tipo) {
            case "cocinero":
                FCocinero fc = new FCocinero(usr);
                cnx.desconectar();
                this.dispose();
                fc.setVisible(true);
                break;
            case "mesero":
                FMesero fme = new FMesero(usr);
                cnx.desconectar();
                this.dispose();
                fme.setVisible(true);
                break;
            case "cajero":
                FCajero fca = new FCajero(usr);
                cnx.desconectar();
                this.dispose();
                fca.setVisible(true);
                break;
            case "gerente":
                FGerente fg = new FGerente(usr);
                cnx.desconectar();
                this.dispose();
                fg.setVisible(true);
                break;
            case "":
                JOptionPane.showMessageDialog(this, "Credenciales incorrectas");
                intentos++;
                if (intentos >= 3) {
                    JOptionPane.showMessageDialog(this, "Número de intentos excedidos");
                    System.exit(0);
                }
                break;

        }
    }//GEN-LAST:event_BAceptarActionPerformed

